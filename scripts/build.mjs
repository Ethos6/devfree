#!/usr/bin/env node
// Generates the service list inside README.md and the JSON API used by the website.
//   node scripts/build.mjs          write README.md and site/api/*.json
//   node scripts/build.mjs --check  fail if README.md is out of date (used in CI)
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, allServices, loadCategories, slug } from './lib.mjs';

const START = '<!-- services:start (generated by scripts/build.mjs, edit data/*.json instead) -->';
const END = '<!-- services:end -->';
const check = process.argv.includes('--check');

const categories = loadCategories().sort((a, b) => a.category.localeCompare(b.category));
const services = allServices(categories);
const oldest = services.map((s) => s.checked).sort()[0];

const md = (text) => String(text).replace(/([\\`*_[\]<>|])/g, '\\$1');

function entry(s) {
  const badges = [];
  if (s.credit_card_required === false) badges.push('no card');
  if (s.credit_card_required === true) badges.push('card required');
  if (s.open_source) badges.push('open source');
  const lines = [
    `- **[${md(s.name)}](${s.url})**: ${md(s.description)}${badges.length ? ` _(${badges.join(', ')})_` : ''}`,
    ...s.free_tier.map((l) => `  - ${md(l)}`),
  ];
  if (s.notes) lines.push(`  - Note: ${md(s.notes)}`);
  lines.push(`  - [Pricing page](${s.pricing_url}) · checked ${s.checked}`);
  return lines.join('\n');
}

const toc = categories.map((c) => `- [${c.category}](#${slug(c.category)}) (${c.services.length})`).join('\n');
const body = categories
  .map((c) => [`### ${c.category}`, '', `${c.description}`, '', ...c.services.map((s) => entry({ ...s }))].join('\n'))
  .join('\n\n');

const generated = [
  START,
  '',
  `**${services.length} services in ${categories.length} categories.** Every entry was checked against the provider's own pricing page; the oldest check is from ${oldest}.`,
  '',
  toc,
  '',
  body,
  '',
  END,
].join('\n');

const readmePath = join(ROOT, 'README.md');
const readme = readFileSync(readmePath, 'utf8');
const startIdx = readme.indexOf(START);
const endIdx = readme.indexOf(END);
if (startIdx < 0 || endIdx < 0) {
  console.error('README.md is missing the services:start / services:end markers.');
  process.exit(1);
}
const nextReadme = readme.slice(0, startIdx) + generated + readme.slice(endIdx + END.length);

if (check) {
  if (nextReadme !== readme) {
    console.error('✖ README.md is out of date. Run `npm run build` and commit the result.');
    process.exit(1);
  }
  console.log('✔ README.md is up to date');
  process.exit(0);
}

writeFileSync(readmePath, nextReadme);

// JSON API for the website and for anyone who wants the data.
const apiDir = join(ROOT, 'site', 'api');
mkdirSync(apiDir, { recursive: true });
const publicServices = services.map(({ categoryTitle, ...s }) => s);
writeFileSync(
  join(apiDir, 'services.json'),
  `${JSON.stringify({ generated: new Date().toISOString().slice(0, 10), count: publicServices.length, services: publicServices }, null, 2)}\n`,
);
writeFileSync(
  join(apiDir, 'categories.json'),
  `${JSON.stringify(categories.map((c) => ({ id: c.id, title: c.category, description: c.description, count: c.services.length })), null, 2)}\n`,
);
console.log(`✔ Built README.md and site/api for ${services.length} services`);
